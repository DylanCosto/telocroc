/// `annotate_interstitial_tel`: does `pos` fall within 2 kb of a known interstitial
/// telomere region on contig `chr` (e.g. `t2t-chm13_chr2q`)?
pub fn is_interstitial_tel(chr: &str, pos: i64) -> bool {
    const BUFFER: i64 = 2000;
    INTERSTITIAL_TEL_REGIONS.iter().any(|&(c, start, end)| c == chr && pos >= start - BUFFER && pos <= end + BUFFER)
}

/// N50 of a non-empty list of lengths.
pub fn n50(lengths: &[i64]) -> i64 {
    let mut sorted = lengths.to_vec();
    sorted.sort_unstable_by(|a, b| b.cmp(a));
    let total: i64 = sorted.iter().sum();
    let threshold = total as f64 * 0.5;
    let mut cumulative = 0;
    for len in sorted {
        cumulative += len;
        if cumulative as f64 >= threshold {
            return len;
        }
    }
    0
}

/// `strip_paths_from_string`: keep only the last path component of an argument.
pub fn strip_path(s: &str) -> String {
    match s.rsplit_once('/') {
        Some((_, "")) => "./".to_string(),
        Some((_, last)) => last.to_string(),
        None => s.to_string(),
    }
}

